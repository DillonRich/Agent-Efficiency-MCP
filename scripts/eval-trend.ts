/**
 * Build a markdown trend of recent eval scorecards.
 */
import {
  existsSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  writeFileSync,
} from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const resultsDir = join(root, "fixtures/eval/results");
const outMd = join(root, "docs/EVAL_TREND.md");

interface Summary {
  provider?: string;
  timestamp?: string;
  totals?: {
    mean_composite?: number;
    fails?: number;
    pass_rates_pct?: Record<string, number>;
  };
  gates_passed?: boolean;
}

function main(): void {
  mkdirSync(resultsDir, { recursive: true });
  const files = readdirSync(resultsDir)
    .filter(
      (f) =>
        f.endsWith(".json") &&
        !f.includes("latest") &&
        !f.includes("quality-loop") &&
        !f.includes("context-budget"),
    )
    .map((f) => {
      const full = join(resultsDir, f);
      try {
        const j = JSON.parse(readFileSync(full, "utf8")) as Summary;
        return { f, j, t: j.timestamp || f };
      } catch {
        return null;
      }
    })
    .filter(Boolean) as Array<{ f: string; j: Summary; t: string }>;

  files.sort((a, b) => (a.t < b.t ? 1 : -1));
  const latest = files.slice(0, 10);

  const rows = latest.map((x) => {
    const mean = x.j.totals?.mean_composite ?? "?";
    const fails = x.j.totals?.fails ?? "?";
    const gates = x.j.gates_passed ? "yes" : "no";
    const r4 = x.j.totals?.pass_rates_pct?.r4_objective_density ?? "?";
    const r9 = x.j.totals?.pass_rates_pct?.r9_no_tour ?? "?";
    return `| ${x.j.timestamp ?? x.f} | ${x.j.provider ?? "?"} | ${mean} | ${fails} | ${r4} | ${r9} | ${gates} |`;
  });

  const md = `# Eval trend (last ${latest.length})

Auto-generated by \`npm run eval-trend\`. Do not hand-edit.

| Timestamp | Provider | mean | fails | R4% | R9% | gates |
|-----------|----------|-----:|------:|----:|----:|-------|
${rows.join("\n") || "| (no scorecards yet) | | | | | | |"}

Targets: mean ≥ 80; R1/R3 ≥ 95%; R6/R9 ≥ 90%; fails = 0.
`;

  writeFileSync(outMd, md, "utf8");
  const latestPath = join(resultsDir, "scorecard-latest.json");
  if (existsSync(latestPath)) {
    /* keep */
  }
  console.error(`Wrote ${outMd} (${latest.length} rows)`);
}

main();
